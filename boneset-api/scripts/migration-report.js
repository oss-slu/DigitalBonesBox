// boneset-api/scripts/migration-report.js
// Imports every boneset, bone, and bone part the viewer lists (in memory only; no scene is
// saved) and writes a summary of what migrates to the scene format and what doesn't.
// Issue #468 (parent #463).
//
// Usage (from the project root):
//   node boneset-api/scripts/migration-report.js
// Output:
//   docs/migration-validation/report.md
const fs = require("fs");
const path = require("path");
const { buildLegacyImages } = require("../legacyImport");
const { buildLegacyAnnotations } = require("../legacyAnnotations");

const DATA_DIR = path.join(__dirname, "..", "data");
const OUTPUT = path.join(__dirname, "..", "..", "docs", "migration-validation", "report.md");
const BONESETS = ["bony_pelvis", "skull", "thorax", "vertebrae", "upper_limb", "lower_limb"];

function readJson(file) {
    try {
        return JSON.parse(fs.readFileSync(file, "utf8"));
    } catch {
        return null;
    }
}

/**
 * Every item in the viewer's dropdowns, in dropdown order: { boneset, type, id }.
 */
function listItems() {
    const items = [];
    for (const bonesetId of BONESETS) {
        const boneset = readJson(path.join(DATA_DIR, "boneset", `${bonesetId}.json`));
        if (!boneset) continue;
        items.push({ boneset: bonesetId, type: "boneset", id: bonesetId });
        for (const boneId of boneset.bones || []) {
            let bone = readJson(path.join(DATA_DIR, "bones", `${boneId}.json`));
            if (Array.isArray(bone)) bone = bone[0];
            items.push({ boneset: bonesetId, type: "bone", id: boneId });
            for (const partId of (bone && bone.subBones) || []) {
                items.push({ boneset: bonesetId, type: "bone part", id: partId });
            }
        }
    }
    return items;
}

/**
 * Imports one item the way the Scene Editor's "Import bone images" does with both
 * "Also import" boxes ticked, and summarizes the result.
 */
async function migrate(item) {
    let imported;
    try {
        imported = await buildLegacyImages(item.id);
    } catch (error) {
        return { ...item, status: "not imported", note: error.message };
    }
    if (imported.images.length === 0) {
        return { ...item, status: "not imported", note: "No images listed for this item" };
    }

    const result = await buildLegacyAnnotations(item.id, imported.images, {
        include: { labels: true, regions: true },
        allImagesImported: imported.images.length === imported.totalImages,
    });
    return {
        ...item,
        status: "imported",
        images: imported.images.length,
        labels: result.counts.labels,
        lines: result.counts.lines,
        regions: result.counts.regions,
        note: [...imported.warnings, ...result.warnings].map((w) => `${w.filename || w.item}: ${w.reason}`).join("; "),
    };
}

function toMarkdown(rows) {
    const imported = rows.filter((row) => row.status === "imported");
    const sum = (key) => imported.reduce((total, row) => total + row[key], 0);
    const count = (predicate) => imported.filter(predicate).length;
    const lines = [
        "# Migration report",
        "",
        "Generated by `node boneset-api/scripts/migration-report.js` (Issue #468). Every item in the",
        "viewer's dropdowns is imported in memory with its images, labels, pointer lines, and colored",
        "regions, the way the Scene Editor's **Import bone images** does. Nothing is saved.",
        "",
        "## Summary",
        "",
        "| | Count |",
        "|---|---|",
        `| Items in the viewer's dropdowns | ${rows.length} |`,
        `| Imported | ${imported.length} |`,
        `| Not imported (no content or invalid id) | ${rows.length - imported.length} |`,
        `| Imported with 1 image | ${count((row) => row.images === 1)} |`,
        `| Imported with 2 images | ${count((row) => row.images === 2)} |`,
        `| Imported with 3 or more images | ${count((row) => row.images >= 3)} |`,
        `| Images | ${sum("images")} |`,
        `| Labels | ${sum("labels")} |`,
        `| Pointer lines | ${sum("lines")} |`,
        `| Colored regions | ${sum("regions")} |`,
        `| Imported items with import notes | ${count((row) => row.note.length > 0)} |`,
        "",
        "## Every item",
        "",
        "| Boneset | Type | Item | Status | Images | Labels | Lines | Regions | Notes |",
        "|---|---|---|---|---|---|---|---|---|",
    ];
    for (const row of rows) {
        if (row.status !== "imported") {
            lines.push(`| ${row.boneset} | ${row.type} | \`${row.id}\` | not imported | | | | | ${row.note} |`);
            continue;
        }
        lines.push(`| ${row.boneset} | ${row.type} | \`${row.id}\` | imported | ${row.images} | ` +
            `${row.labels} | ${row.lines} | ${row.regions} | ${row.note} |`);
    }
    return `${lines.join("\n")}\n`;
}

async function main() {
    const rows = [];
    for (const item of listItems()) rows.push(await migrate(item));
    fs.mkdirSync(path.dirname(OUTPUT), { recursive: true });
    fs.writeFileSync(OUTPUT, toMarkdown(rows));
    console.log(`Wrote ${path.relative(process.cwd(), OUTPUT)} (${rows.length} items)`);
}

if (require.main === module) {
    main().catch((error) => {
        console.error(error);
        process.exitCode = 1;
    });
}

module.exports = { listItems, migrate, toMarkdown };